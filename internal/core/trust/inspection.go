// matchInspection returns the product whose name appears in this issuer, or nil.
//
// NIL IS THE ORDINARY ANSWER and it means "not named", never "not inspection".
// The difference is what the caveat beside the finding exists to say.
//
// IT FAILS CLOSED IN EVERY DIRECTION. A distinguished name this splitter cannot
// make sense of produces no match rather than a guess, because the cost of the
// two mistakes is not symmetric: an unnamed appliance costs a sentence, and a
// name printed over an ordinary corporate authority is what inviolable rule 21
// calls harm.
//
// FIRST ENTRY WINS, IN DECLARATION ORDER. Two entries matching one issuer would
// otherwise be answered differently depending on map iteration, and a report
// that says something different on every run is not a report.
func matchInspection(issuer string) *InspectionProduct {
	if issuer == "" {
		return nil
	}
	attributes := splitDistinguishedName(issuer)
	if len(attributes) == 0 {
		return nil
	}
	for i, product := range inspectionProducts {
		for _, attribute := range attributes {
			if !strings.EqualFold(attribute.kind, product.Attribute) {
				continue
			}
			if report.ContainsWord(attribute.value, product.Match) {
				return &inspectionProducts[i]
			}
		}
	}
	return nil
}

// attribute is one type-and-value pair out of a distinguished name.
type attribute struct {
	kind  string
	value string
}

// splitDistinguishedName takes apart the string form of an issuer.
//
// IT PARSES WHAT WE OURSELVES PRODUCED, and that is what makes it small enough
// to be honest about. The only distinguished names reaching this function were
// rendered by one function on the adapter side, from crypto/x509's pkix.Name -
// so the escaping is RFC 2253's, and the shape is comma separated pairs with a
// backslash escaping any comma, plus, quote, backslash, angle bracket, semicolon
// or leading space inside a value.
//
// WHAT IT DELIBERATELY DOES NOT DO. It does not decode the hash-prefixed
// hexadecimal form, does not split a multi-valued relative name on its plus, and
// does not resolve an attribute written as a bare object identifier. Each of
// those produces a value this function does not recognise, which produces no
// match - the direction that costs a sentence rather than an accusation.
func splitDistinguishedName(name string) []attribute {
	var attributes []attribute
	var current strings.Builder
	escaped := false
	pairs := []string{}
	for _, r := range name {
		switch {
		case escaped:
			current.WriteRune(r)
			escaped = false
		case r == '\\':
			// The backslash itself is dropped: what matters here is the
			// character it protected, not how it was written on the wire.
			escaped = true
		case r == ',':
			pairs = append(pairs, current.String())
			current.Reset()
		default:
			current.WriteRune(r)
		}
	}
	pairs = append(pairs, current.String())

	for _, pair := range pairs {
		kind, value, found := strings.Cut(pair, "=")
		if !found {
			// A fragment with no equals sign is not an attribute, and guessing
			// which one it was meant to be is exactly the invention this whole
			// function refuses.
			continue
		}
		kind = strings.TrimSpace(kind)
		value = strings.TrimSpace(value)
		if kind == "" || value == "" {
			continue
		}
		attributes = append(attributes, attribute{kind: kind, value: value})
	}
	return attributes
}
