// This file is the list of TLS inspection products and the rule that matches a
// certificate's issuer against it. IT DECIDES NOTHING - authority.go does, and
// the guard on that file is what keeps it the only place that can.
//
// WHAT THE LIST IS FOR, AND WHAT IT IS NOT FOR - O11, closed 2026-08-02 and not
// reopened here. The BASIC test for a signer that this machine holds unevenly is
// structural, it runs on every connection, and it does not consult this file at
// all. This list exists to NAME what was already found. A product that is not on
// it is not thereby innocent - it is unnamed, and the report says so in its own
// words rather than by omission.
//
// WHY THAT ORDER RATHER THAN THE OBVIOUS ONE. Every vendor here lets an
// organisation supply its own certificate authority instead of the product's,
// and the appliance then signs with a name belonging to the CUSTOMER. Detection
// by name would therefore miss precisely the environments this program is built
// for. It would also miss every appliance nobody has heard of.
//
// THE BAR FOR AN ENTRY, AND IT IS THE REASON THIS LIST IS SHORT. Inviolable rule
// 18: a claim about somebody else's runtime carries a source that was read at
// the source, with a date. Two kinds of source clear it - the product's own
// SOURCE CODE, which is the strongest because the name is generated by a line
// that can be read, and the vendor's own DOCUMENTATION. What does not clear it:
// a search result, a third-party blog, a certificate somebody posted, and this
// program's own guess about what a name probably is. Researched 2026-09-01:
// Fortinet documents the certificate OBJECT name Fortinet_CA_SSL, which is not a
// distinguished name at all; Zscaler's help portal renders with a script and
// could not be read; PortSwigger's and Telerik's own pages describe their
// certificates without stating the subject. None of them got an entry, and that
// refusal is written down in OBS86 rather than left as a short list nobody
// explains.

// InspectionProduct is one entry: a name this program is prepared to print, the
// place in an issuer's distinguished name where that name appears, and the pair
// inviolable rule 18 requires beside any claim about somebody else's product.
type InspectionProduct struct {
	// Product is how this program spells the name, and it is OUR prose. It is
	// what a reader sees, so it is written the way the vendor writes it rather
	// than the way the certificate happens to.
	Product string
	// Attribute is which part of the issuer's distinguished name carries the
	// name - "CN" or "O".
	//
	// AN ENTRY NAMES ONE ATTRIBUTE RATHER THAN SEARCHING THE WHOLE NAME, and
	// that is the difference between naming a product and accusing a company
	// called Fortinetworks. A distinguished name also carries a country, a
	// locality and an organisational unit, none of which say who built the
	// appliance.
	Attribute string
	// Match is the token sequence looked for inside that attribute, compared
	// without regard to case and only on whole words.
	Match string
	// Source and Evidence are the rule 18 pair, the same shape Descriptor
	// carries one file over, and the reason is the same: a rule kept by good
	// intentions is the one this project said it would break first.
	Source   Source
	Evidence string
}

