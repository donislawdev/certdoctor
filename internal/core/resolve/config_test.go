// TestTheHostsLineIsReadAndItsActionsAreNot is the nsswitch half.
//
// The bracketed parts say what to do about a result, not where to look for one.
// Counting one as a source would put [NOTFOUND=return] in a report as a place
// this machine looks up names.
func TestTheHostsLineIsReadAndItsActionsAreNot(t *testing.T) {
	const file = "passwd:\tfiles systemd\n" +
		"hosts:\tfiles mdns4_minimal [NOTFOUND=return] dns myhostname\n" +
		"networks:\tfiles\n"

	got, err := ParseNameSources([]byte(file))
	if err != nil {
		t.Fatalf("an ordinary nsswitch.conf was refused: %v", err)
	}
	if !got.Declared {
		t.Fatal("a file naming a hosts line came back saying it named none")
	}
	want := []string{"files", "mdns4_minimal", "dns", "myhostname"}
	if len(got.Order) != len(want) {
		t.Fatalf("the sources came back as %v", got.Order)
	}
	for i := range want {
		if got.Order[i] != want[i] {
			t.Fatalf("the sources came back as %v", got.Order)
		}
	}
	if !got.ConsultsHostsFile() {
		t.Error("a hosts line naming files came back saying this system does not read the hosts file")
	}
}

// TestAStrayBracketIsNotReadAsASource is a defect the fuzzer found within a
// second and that no hand written case here had, because nobody writes an
// nsswitch.conf this way on purpose.
//
// The first version looked at the first and last character of a field, so a field
// like `0]` fell through as an ordinary name - and would have been reported as a
// place this system looks up names. It is pinned here as well as in the corpus,
// because a corpus entry says "this input once failed" and a test says which rule
// it belongs to.
func TestAStrayBracketIsNotReadAsASource(t *testing.T) {
	for _, line := range []string{
		"hosts: 0]",
		"hosts: files ] dns",
		"hosts: files [NOTFOUND=return dns",
		"hosts: ]]] files",
	} {
		got, err := ParseNameSources([]byte(line + "\n"))
		if err != nil {
			t.Fatalf("%q was refused: %v", line, err)
		}
		for _, source := range got.Order {
			if strings.ContainsAny(source, "[]") {
				t.Errorf("%q produced the source %q, which is a broken action rather than a place to look",
					line, source)
			}
		}
	}
}

// TestAFileWithNoHostsLineIsNotAFileSayingNothingIsConsulted covers the
// difference Declared exists for. Reporting the two alike would say "this system
// does not consult /etc/hosts" about a machine whose configuration lives
// somewhere else entirely.
func TestAFileWithNoHostsLineIsNotAFileSayingNothingIsConsulted(t *testing.T) {
	got, err := ParseNameSources([]byte("passwd:\tfiles\ngroup:\tfiles\n"))
	if err != nil {
		t.Fatalf("the file was refused: %v", err)
	}
	if got.Declared {
		t.Error("a file with no hosts line came back saying it had one")
	}
	if got.ConsultsHostsFile() {
		t.Error("a file that says nothing about hosts was read as saying files are not consulted")
	}

	declared, err := ParseNameSources([]byte("hosts:\tdns\n"))
	if err != nil {
		t.Fatalf("the file was refused: %v", err)
	}
	if !declared.Declared || declared.ConsultsHostsFile() {
		t.Errorf("a hosts line naming only dns came back as %+v", declared)
	}
}

// TestTheLastHostsLineWins covers the rule the C library follows. Merging two
// lines would report an order this system does not use.
func TestTheLastHostsLineWins(t *testing.T) {
	got, err := ParseNameSources([]byte("hosts:\tfiles\nhosts:\tdns\n"))
	if err != nil {
		t.Fatalf("the file was refused: %v", err)
	}
	if len(got.Order) != 1 || got.Order[0] != "dns" {
		t.Errorf("two hosts lines were merged: %v", got.Order)
	}
}

// TestTheEncodingContractCoversBothFiles keeps the rule in one place. Two parsers
// with two encoding rules is one parser with a rule and one without, six months
// from now.
func TestTheEncodingContractCoversBothFiles(t *testing.T) {
	file := append([]byte{0xff, 0xfe}, "hosts:\tfiles dns\n"...)
	if _, err := ParseNameSources(file); err == nil {
		t.Error("nsswitch.conf in UTF-16 was read as UTF-8, so the hosts order came back empty")
	}

	marked := append([]byte{0xef, 0xbb, 0xbf}, "hosts:\tfiles dns\n"...)
	got, err := ParseNameSources(marked)
	if err != nil {
		t.Fatalf("nsswitch.conf with a UTF-8 byte order mark was refused: %v", err)
	}
	if !got.Declared {
		t.Error("a byte order mark hid the hosts line")
	}
}

