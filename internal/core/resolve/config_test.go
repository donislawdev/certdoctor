// TestBothCommentSpellingsAndBothLineEndingsAreHandled covers the shapes a file
// picks up in transit. A carriage return left on a value makes an address that
// does not parse, so the row would be dropped as malformed on a file that is fine.
//
// WHAT HANDLES THE CARRIAGE RETURN IS NOT WHAT WAS WRITTEN FOR IT. lines used to
// trim one off each line; the mutation register showed that deleting that changed
// nothing, because directive puts every line through TrimSpace first and \r is
// whitespace. The trim was removed and this test still passes - which is the
// point of keeping it: the property is CRLF files being read correctly, not any
// particular line doing it.
func TestBothCommentSpellingsAndBothLineEndingsAreHandled(t *testing.T) {
	const file = "# a hash comment\r\n; a semicolon comment\r\n\r\nnameserver 9.9.9.9\r\n"

	got, err := ParseResolverConfig([]byte(file))
	if err != nil {
		t.Fatalf("the file was refused: %v", err)
	}
	if len(got.Nameservers) != 1 || got.Nameservers[0] != "9.9.9.9" {
		t.Errorf("a carriage return or a comment cost the file its nameserver: %v", got.Nameservers)
	}
	if len(got.Skipped) != 0 {
		t.Errorf("a comment was reported as a skipped directive: %v", got.Skipped)
	}
}

// TestAHashInsideAValueIsNotACommentPins the rule that would cut a value short.
