// TestAnOrdinaryResolverConfigIsRead is the other side of every refusal in this
// file. Rules that only refuse can be written to refuse everything, and every
// hostile case below would still pass.
//
// The two files are the ones measured on 2026-08-05 - alpine and WSL Ubuntu -
// rather than ones invented for the test.
func TestAnOrdinaryResolverConfigIsRead(t *testing.T) {
	const file = "# Generated by something\n" +
		"nameserver 192.168.65.7\n" +
		"nameserver 1.1.1.1\n" +
		"search corp.example lan\n" +
		"options ndots:0\n"

	got, err := ParseResolverConfig([]byte(file))
	if err != nil {
		t.Fatalf("an ordinary resolv.conf was refused: %v", err)
	}
	if len(got.Nameservers) != 2 || got.Nameservers[0] != "192.168.65.7" || got.Nameservers[1] != "1.1.1.1" {
		t.Errorf("the nameservers came back as %v", got.Nameservers)
	}
	if len(got.Search) != 2 || got.Search[0] != "corp.example" {
		t.Errorf("the search list came back as %v", got.Search)
	}
	// The options line is named rather than dropped. A reader has to be able to
	// tell "there was nothing else in this file" from "this parser ignored it".
	if len(got.Skipped) != 1 || got.Skipped[0].Line != 5 {
		t.Errorf("the options line was not named as skipped: %v", got.Skipped)
	}
}

// TestTheNameserverOrderIsTheFilesOrder pins the property that a map keyed by
// line number destroyed in the first version of this parser.
//
// The resolver tries them in the order the file lists them, so the order IS the
// configuration. Ranging over a map would have produced a different report on
// every run, each one looking perfectly plausible.
func TestTheNameserverOrderIsTheFilesOrder(t *testing.T) {
	var file strings.Builder
	want := []string{"10.0.0.1", "10.0.0.2", "10.0.0.3", "10.0.0.4", "10.0.0.5", "10.0.0.6"}
	for _, address := range want {
		file.WriteString("nameserver " + address + "\n")
	}

	// THE FILE STILL HAS SIX LINES AFTER MaxNameservers ARRIVED, and that is what
	// keeps this test as sharp as it was. Only three addresses come back now, and
	// three entries out of a map agree by accident far too often - so the other
	// three are checked where they went: Skipped carries lines 4, 5 and 6, in the
	// file's order. The failure this guards against, a parser keyed by line
	// number ranging over a map, still has six things to put in the wrong order.
	for attempt := 0; attempt < 20; attempt++ {
		got, err := ParseResolverConfig([]byte(file.String()))
		if err != nil {
			t.Fatalf("an ordinary resolv.conf was refused: %v", err)
		}
		if len(got.Nameservers) != MaxNameservers {
			t.Fatalf("attempt %d kept %d nameserver(s), and the limit is %d", attempt, len(got.Nameservers), MaxNameservers)
		}
		for i := range got.Nameservers {
			if got.Nameservers[i] != want[i] {
				t.Fatalf("attempt %d read the file out of order: %v", attempt, got.Nameservers)
			}
		}
		if len(got.Skipped) != len(want)-MaxNameservers {
			t.Fatalf("attempt %d named %d skipped line(s) for %d lines past the limit: %v",
				attempt, len(got.Skipped), len(want)-MaxNameservers, got.Skipped)
		}
		for i, skipped := range got.Skipped {
			if skipped.Line != MaxNameservers+1+i {
				t.Fatalf("attempt %d reported the skipped lines out of order: %v", attempt, got.Skipped)
			}
		}
	}
}

// TestThisRunAsksNoMoreResolversThanThePlatformWould is the limit, and it is a
// correctness property before it is a limit.
//
// MEASURED AT SOURCE 2026-09-04, twice: Go's own dnsconfig_unix.go takes a
// nameserver only while len(conf.servers) < 3, and glibc declares MAXNS 3. The
// system view goes through Go's resolver, so a direct view asking a fourth
// resolver compares itself against a lens that can never have asked it - and any
// disagreement it then reports was manufactured by this program.
func TestThisRunAsksNoMoreResolversThanThePlatformWould(t *testing.T) {
	got, err := ParseResolverConfig([]byte(
		"nameserver 10.0.0.1\nnameserver 10.0.0.2\nnameserver 10.0.0.3\nnameserver 10.0.0.4\n"))
	if err != nil {
		t.Fatalf("an ordinary resolv.conf was refused: %v", err)
	}
	if len(got.Nameservers) != 3 {
		t.Fatalf("kept %v, and the platform reads three", got.Nameservers)
	}
	if len(got.Skipped) != 1 || got.Skipped[0].Line != 4 {
		t.Fatalf("the fourth line was not named as skipped: %v", got.Skipped)
	}
	if !strings.Contains(got.Skipped[0].Why, "three") {
		t.Errorf("the reason does not say what the limit is: %q", got.Skipped[0].Why)
	}
}

// TestARepeatedResolverIsConsultedOnceAndCountedOnce covers both halves of the
// duplicate rule, and they pull in opposite directions on purpose.
//
// A repeat must not become a second query, a second row and a second pseudonym.
// It must still COST one of the three slots, because the reader this list
// mirrors appends duplicates and stops at three regardless - so a file naming
// one address three times leaves that platform with one resolver and no room
// for a fourth line, and this program has to arrive at the same population.
func TestARepeatedResolverIsConsultedOnceAndCountedOnce(t *testing.T) {
	got, err := ParseResolverConfig([]byte(
		"nameserver 10.0.0.1\nnameserver 10.0.0.1\nnameserver 10.0.0.1\nnameserver 10.0.0.9\n"))
	if err != nil {
		t.Fatalf("an ordinary resolv.conf was refused: %v", err)
	}
	if len(got.Nameservers) != 1 || got.Nameservers[0] != "10.0.0.1" {
		t.Fatalf("a repeated address was consulted more than once: %v", got.Nameservers)
	}
	if len(got.Skipped) != 3 {
		t.Fatalf("%d skipped line(s) for two repeats and one line past the limit: %v", len(got.Skipped), got.Skipped)
	}
	if !strings.Contains(got.Skipped[0].Why, "already") {
		t.Errorf("the repeat was not named as one: %q", got.Skipped[0].Why)
	}
	// The fourth line is past the limit BECAUSE the repeats used slots, which is
	// the half that keeps this list the same population the platform reads.
	if !strings.Contains(got.Skipped[2].Why, "three") {
		t.Errorf("the fourth line was not refused by the limit: %q", got.Skipped[2].Why)
	}
}

// TestAByteOrderMarkDoesNotEatTheFirstDirective is measured shape one.
//
// A UTF-8 mark glues itself to the first keyword, so `nameserver` is not
// recognised - and the file reads as one with a resolver missing. Nothing about
// the result looks wrong: it is a valid parse of a file that says less.
func TestAByteOrderMarkDoesNotEatTheFirstDirective(t *testing.T) {
	file := append([]byte{0xef, 0xbb, 0xbf}, "nameserver 1.1.1.1\nnameserver 8.8.8.8\n"...)

	got, err := ParseResolverConfig(file)
	if err != nil {
		t.Fatalf("a file with a UTF-8 byte order mark was refused: %v", err)
	}
	if len(got.Nameservers) != 2 {
		t.Errorf("a byte order mark cost the file %d of its 2 nameservers: %v", 2-len(got.Nameservers), got.Nameservers)
	}
}

// TestAUTF16FileIsRefusedRatherThanReadAsEmpty is measured shape two, and it is
// the one that produces a confident untruth rather than a small loss.
//
// Read as UTF-8 the whole file is nonsense, so the parse succeeds and reports
// zero nameservers - "this machine has no resolver configured", about a machine
// that has two.
func TestAUTF16FileIsRefusedRatherThanReadAsEmpty(t *testing.T) {
	for _, c := range []struct {
		name string
		bom  []byte
	}{
		{"little endian", []byte{0xff, 0xfe}},
		{"big endian", []byte{0xfe, 0xff}},
	} {
		t.Run(c.name, func(t *testing.T) {
			file := append(append([]byte{}, c.bom...), "nameserver 1.1.1.1\n"...)

			_, err := ParseResolverConfig(file)
			if err == nil {
				t.Fatal("a UTF-16 file was read as UTF-8, which reports a configured machine as an unconfigured one")
			}
			var unsupported *UnsupportedEncoding
			if !errors.As(err, &unsupported) {
				t.Errorf("the refusal does not say the encoding is why: %v", err)
			}
			if !strings.Contains(err.Error(), "UTF-16") {
				t.Errorf("the refusal does not name the encoding, so nobody knows what to do about it: %v", err)
			}
		})
	}
}

// TestAValueThatIsNotTextIsNamedRatherThanPassedOn is measured shapes three and
// four together.
//
// A byte outside UTF-8 would travel into --json and produce a document its
// consumer cannot decode. A NUL renders identically to a clean value on every
// surface, so it travels invisibly - which is worse, because nobody would even
// look for it.
func TestAValueThatIsNotTextIsNamedRatherThanPassedOn(t *testing.T) {
	cases := map[string]string{
		"a byte outside UTF-8": "nameserver 1.1.1.\x9c\n",
		"a NUL inside a value": "nameserver 1.1.1.1\x00\n",
		"a control character":  "nameserver 1.1.1.1\x01\n",
	}

	for name, file := range cases {
		t.Run(name, func(t *testing.T) {
			got, err := ParseResolverConfig([]byte(file))
			if err != nil {
				t.Fatalf("a file with one bad value was refused whole: %v", err)
			}
			if len(got.Nameservers) != 0 {
				t.Errorf("a value that is not text reached the report: %q", got.Nameservers)
			}
			if len(got.Skipped) != 1 || got.Skipped[0].Why != whyNotText {
				t.Errorf("the dropped line was not named as unreadable: %v", got.Skipped)
			}
			if got.Skipped[0].Line != 1 {
				t.Errorf("the dropped line was reported at line %d", got.Skipped[0].Line)
			}
		})
	}
}

// TestAnUnreadableSearchListIsDroppedWhole covers the rule for the directive
// that carries several values at once.
//
// THE WHOLE LINE GOES RATHER THAN THE OFFENDING WORD, and that is the choice
// worth pinning. A search list with one domain silently missing resolves names
// differently from the one on disk, and nothing in the report would say a word had
// gone - so the reader would be comparing a plausible list against the wrong file.
func TestAnUnreadableSearchListIsDroppedWhole(t *testing.T) {
	got, err := ParseResolverConfig([]byte("search a.example \x9c.example c.example\n"))
	if err != nil {
		t.Fatalf("the file was refused whole: %v", err)
	}
	if len(got.Search) != 0 {
		t.Errorf("part of an unreadable search line reached the report: %v", got.Search)
	}
	if len(got.Skipped) != 1 || got.Skipped[0].Why != whyNotText {
		t.Errorf("the dropped search line was not named: %v", got.Skipped)
	}
}

// TestAnUnreadableDomainDirectiveClearsWhatItSupersedes is the uncomfortable half
// of the last-one-wins rule.
//
// The domain line replaces the search list, so a search list read earlier is
// superseded whether or not this line can be read. Keeping the earlier one would
// show a list this machine no longer uses, presented as current.
func TestAnUnreadableDomainDirectiveClearsWhatItSupersedes(t *testing.T) {
	got, err := ParseResolverConfig([]byte("search a.example b.example\ndomain \x00c.example\n"))
	if err != nil {
		t.Fatalf("the file was refused whole: %v", err)
	}
	if len(got.Search) != 0 {
		t.Errorf("a superseded search list was reported as current: %v", got.Search)
	}
	if len(got.Skipped) != 1 || got.Skipped[0].Line != 2 || got.Skipped[0].Why != whyNotText {
		t.Errorf("the unreadable domain line was not named: %v", got.Skipped)
	}
}

